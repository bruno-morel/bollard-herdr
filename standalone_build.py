#!/usr/bin/env python3
"""Generate standalone distributions from the maintained layout views, never forks."""
import argparse
import json
from pathlib import Path
from desktop_build import check as check_shared

ROOT = Path(__file__).resolve().parent


def plan(root=ROOT):
    check_shared(root)
    mods = root / "herdr/mods"
    result = {}
    common = {
        "ui.js": root / "desktop/shared/ui.js",
        "panel-host.js": root / "desktop/standalone/panel-host.js",
        "scope.js": root / "desktop/shared/scope.js",
        "signals.js": root / "desktop/shared/signals.js",
        "helper.js": root / "desktop/shared/helper.js",
        "routing.js": root / "desktop/shared/routing-core.js",
    }
    for kind in ("files", "docker"):
        name = "bollard-" + kind
        out = root / "packages" / kind
        sources = dict(common)
        sources["main.js"] = root / "desktop/standalone" / (kind + "-main.js")
        if kind == "files":
            sources.update(
                {
                    "reader.js": mods / "repo-portrait-reader/main.js",
                    "changes.js": mods / "repo-portrait-changes/main.js",
                    "files.js": root / "desktop/shared/files.js",
                }
            )
        else:
            for item in ("docker.js", "docker-state.js", "log-view.js"):
                sources[item] = mods / "repo-portrait" / item
        for relative, source in sources.items():
            text = source.read_text().replace(
                "mods/repo-portrait/icons/", f"mods/{name}/icons/"
            )
            result[out / "mods" / name / relative] = (
                "// Generated by standalone_build.py from "
                + str(source.relative_to(root))
                + "\n"
                + text
            ).encode()
        result[out / "mods" / name / "mod.json"] = (
            json.dumps(
                {"title": "Bollard " + kind.title(), "place": "none", "size": 420}
            )
            + "\n"
        ).encode()
        for source in (mods / "repo-portrait/icons").glob("*.svg"):
            result[out / "mods" / name / "icons" / source.name] = source.read_bytes()
        for script in ("bollard-panel.py", "repo_file_io.py"):
            result[out / "bin" / script] = (root / "bin" / script).read_bytes()
        for legal in ("LICENSE", "THIRD_PARTY_NOTICES.md"):
            result[out / legal] = (root / legal).read_bytes()
    return result


def build(check=False, root=ROOT):
    outputs = plan(root)
    stale = []
    for kind in ("files", "docker"):
        for folder in ("mods", "bin"):
            for path in (root / "packages" / kind / folder).rglob("*"):
                if (
                    path.is_file()
                    and path.suffix in (".js", ".json", ".svg", ".py")
                    and path.name != "jsconfig.json"
                    and path not in outputs
                ):
                    raise ValueError("Orphan packaged source: " + str(path))
    for path, data in outputs.items():
        if not path.exists() or path.read_bytes() != data:
            stale.append(str(path.relative_to(root)))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    if check and stale:
        raise ValueError("Run python3 standalone_build.py: " + ", ".join(stale))
    return len(outputs)


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    print("Verified", build(a.check), "standalone package files.")
