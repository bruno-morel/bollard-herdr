#!/usr/bin/env python3
"""Build self-contained Herdr helpers from shared sources; --check changes nothing."""
import argparse
import json
from pathlib import Path
import tempfile
import os

ROOT = Path(__file__).resolve().parent
MARKER = b"// Generated by desktop_build.py; edit desktop/shared/"


def contained(base, relative):
    path = Path(relative)
    if path.is_absolute() or ".." in path.parts or not path.parts:
        raise ValueError("Invalid package path: " + str(relative))
    target = base / path
    if any(p.is_symlink() for p in (target, *target.parents)):
        raise ValueError("Package paths must not contain symlinks: " + str(target))
    return target


def plan(root=ROOT):
    source = root / "desktop/shared"
    mods = root / "herdr/mods"
    manifest = json.loads((root / "desktop/shared.json").read_text())
    expected_sources = set(manifest)
    actual_sources = {str(p.relative_to(source)) for p in source.rglob("*.js")}
    if expected_sources != actual_sources:
        raise ValueError("Shared source manifest differs from desktop/shared files")
    outputs = {}
    for name, destinations in manifest.items():
        if not isinstance(destinations, list) or not destinations:
            raise ValueError("Shared helper has no destinations: " + name)
        body = contained(source, name).read_bytes()
        if not name.endswith(".js") or b"\0" in body or body.startswith(MARKER):
            raise ValueError("Invalid shared JavaScript source: " + name)
        header = MARKER + name.encode() + b" instead.\n"
        for relative in destinations:
            destination = contained(mods, relative)
            if len(Path(relative).parts) != 2 or destination.suffix != ".js":
                raise ValueError("Expected mod/helper.js: " + relative)
            if not (destination.parent / "mod.json").is_file():
                raise ValueError("Unknown mod: " + relative)
            if destination in outputs:
                raise ValueError("Duplicate generated destination: " + relative)
            outputs[destination] = header + body
    for path in mods.rglob("*.js"):
        if path.read_bytes().startswith(MARKER) and path not in outputs:
            raise ValueError("Orphan generated helper: " + str(path))
    return outputs


def check(root=ROOT):
    outputs = plan(root)
    stale = [str(p.relative_to(root)) for p, data in outputs.items()
             if not p.is_file() or p.read_bytes() != data]
    if stale:
        raise ValueError("Run python3 desktop_build.py; generated helpers differ: "
                         + ", ".join(stale))
    return len(outputs)


def build(root=ROOT):
    outputs = plan(root)  # Validate the whole manifest before writing anything.
    for path, data in outputs.items():
        if path.is_file() and path.read_bytes() == data:
            continue
        fd, temporary = tempfile.mkstemp(dir=path.parent, prefix=".shared-")
        try:
            with os.fdopen(fd, "wb") as stream:
                stream.write(data)
            os.chmod(temporary, 0o644)
            os.replace(temporary, path)
        finally:
            Path(temporary).unlink(missing_ok=True)
    return check(root)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        count = check() if args.check else build()
    except (OSError, ValueError) as exc:
        parser.exit(1, str(exc) + "\n")
    print("Verified", count, "generated Herdr helpers.")


if __name__ == "__main__":
    main()
